# Writes the formal definition and the diagram of every transducer and automaton into
# docs/diagrams. The diagrams use Mermaid, so GitHub shows them directly in the markdown files.
#
# Run from the resumelens folder:
#     python -m resumelens.docs_export

import os

from resumelens.classification.classifier import AUTOMATA
from resumelens.normalization.transducers import CATEGORY_TRANSDUCERS, PREPROCESSING_TRANSDUCER

DOCS_DIR = os.path.join(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))), "docs", "diagrams")

EPSILON = "ε"


def show_symbol(symbol):
    if symbol == " ":
        return "␣"
    return symbol


def show_output(output):
    if len(output) == 0:
        return EPSILON
    return " ".join(output)


def join_symbols(symbols):
    shown = []
    for symbol in symbols:
        shown.append("`" + show_symbol(symbol) + "`")
    return ", ".join(shown)


def transducer_to_markdown(transducer):
    lines = []
    lines.append("M = (Q, Σ, Γ, δ, ω, q0, F)")
    lines.append("")
    lines.append("- **Q** (" + str(len(transducer.states)) + " states) = {" + ", ".join(transducer.states) + "}")
    lines.append("- **Σ** = {" + join_symbols(transducer.input_alphabet) + "}")
    lines.append("- **Γ** = {" + join_symbols(transducer.output_alphabet) + "}")
    lines.append("- **q0** = " + transducer.start_state)
    lines.append("- **F** = {" + ", ".join(transducer.final_states) + "}")
    lines.append("- **δ** and **ω** (" + str(len(transducer.transitions)) + " transitions). "
                 "Each row is δ(state, input) = next state and ω(state, input) = output. "
                 "Every pair that is not in the table is undefined, so the input is rejected.")
    lines.append("")
    lines.append("| state | input | δ: next state | ω: output |")
    lines.append("|---|---|---|---|")
    for from_state, symbol, to_state, output in transducer.transitions:
        lines.append("| " + from_state + " | `" + show_symbol(symbol) + "` | " + to_state + " | " + show_output(output) + " |")
    return "\n".join(lines)


def edge_labels(transducer):
    # Joins all the transitions that go between the same two states into one label
    labels = {}
    order = []
    for from_state, symbol, to_state, output in transducer.transitions:
        key = (from_state, to_state)
        if key not in labels:
            labels[key] = []
            order.append(key)
        labels[key].append(show_symbol(symbol) + " / " + show_output(output))
    return order, labels


def preprocessing_labels():
    # The preprocessing transducer has 71 loops on q0, so the diagram groups them
    return [
        "A..Z / a..z",
        "a..z / a..z",
        "0..9 / 0..9",
        "+ / +,  # / #",
        "␣ . - _ / / " + EPSILON,
    ]


def transducer_to_mermaid(transducer):
    lines = ["```mermaid", "flowchart LR"]
    lines.append("    start(( )) --> " + transducer.start_state)
    for state in transducer.final_states:
        lines.append("    " + state + "(((" + state + ")))")

    if transducer is PREPROCESSING_TRANSDUCER:
        for label in preprocessing_labels():
            lines.append("    q0 -- \"" + label + "\" --> q0")
    else:
        order, labels = edge_labels(transducer)
        for from_state, to_state in order:
            label = ", ".join(labels[(from_state, to_state)])
            lines.append("    " + from_state + " -- \"" + label + "\" --> " + to_state)
    lines.append("```")
    return "\n".join(lines)


def write_transducer_doc(transducer, title, folder):
    text = "# " + title + "\n\n"
    text = text + "_Generated by `python -m resumelens.docs_export` from the pyformlang objects._\n\n"
    text = text + "## Diagram\n\n" + transducer_to_mermaid(transducer) + "\n\n"
    text = text + "## Formal definition\n\n" + transducer_to_markdown(transducer) + "\n"

    os.makedirs(folder, exist_ok=True)
    path = os.path.join(folder, transducer.name.lower() + ".md")
    with open(path, "w", encoding="utf-8") as file:
        file.write(text)
    return path


def export_transducers():
    folder = os.path.join(DOCS_DIR, "transducers")
    paths = [write_transducer_doc(PREPROCESSING_TRANSDUCER, "Transducer PREPROCESSING", folder)]
    for category in CATEGORY_TRANSDUCERS:
        paths.append(write_transducer_doc(CATEGORY_TRANSDUCERS[category], "Transducer " + category, folder))
    return paths


TYPE_NAMES = {
    "DFA": "Deterministic finite automaton (DFA)",
    "NFA": "Nondeterministic finite automaton (NFA)",
    "ENFA": "Nondeterministic finite automaton with ε-transitions (ε-NFA)",
}


def automaton_to_markdown(automaton):
    lines = []
    lines.append("M = (Q, Σ, δ, q0, F)")
    lines.append("")
    lines.append("- **Type**: " + TYPE_NAMES[automaton.automaton_type])
    lines.append("- **Q** = {" + ", ".join(automaton.states) + "}")
    lines.append("- **Σ** = {" + ", ".join(automaton.alphabet) + "}")
    lines.append("- **q0** = " + automaton.start_state)
    lines.append("- **F** = {" + ", ".join(automaton.final_states) + "}")
    lines.append("- **δ** (" + str(len(automaton.transitions)) + " transitions). Pairs that are not in the table go nowhere, so the sequence is rejected.")
    lines.append("")

    # The table joins the transitions that have the same state and target set,
    # for example δ(q1, REACT) = δ(q1, ANGULAR) = δ(q1, VUE) = {q2}
    targets = {}
    order = []
    for from_state, symbol, to_state in automaton.transitions:
        key = (from_state, symbol)
        if key not in targets:
            targets[key] = []
            order.append(key)
        targets[key].append(to_state)

    rows = {}
    row_order = []
    for from_state, symbol in order:
        target = "{" + ", ".join(targets[(from_state, symbol)]) + "}"
        row = (from_state, target)
        if row not in rows:
            rows[row] = []
            row_order.append(row)
        rows[row].append(symbol)

    lines.append("| state | symbols | δ(state, symbol) |")
    lines.append("|---|---|---|")
    for from_state, target in row_order:
        lines.append("| " + from_state + " | " + ", ".join(rows[(from_state, target)]) + " | " + target + " |")

    lines.append("")
    lines.append("Groups of the pattern (in canonical order):")
    lines.append("")
    number = 0
    for group in automaton.profile.groups:
        kind = "required"
        if not group.required:
            kind = "optional"
        lines.append("- q" + str(number) + " → q" + str(number + 1) + ": **" + group.name + "** (" + kind + ") = {" + ", ".join(group.tokens) + "}")
        number = number + 1
    return "\n".join(lines)


def automaton_to_mermaid(automaton):
    lines = ["```mermaid", "flowchart LR"]
    lines.append("    start(( )) --> " + automaton.start_state)
    for state in automaton.final_states:
        lines.append("    " + state + "(((" + state + ")))")

    labels = {}
    order = []
    for from_state, symbol, to_state in automaton.transitions:
        key = (from_state, to_state)
        if key not in labels:
            labels[key] = []
            order.append(key)
        labels[key].append(symbol)
    for from_state, to_state in order:
        label = ", ".join(labels[(from_state, to_state)])
        lines.append("    " + from_state + " -- \"" + label + "\" --> " + to_state)
    lines.append("```")
    return "\n".join(lines)


def write_automaton_doc(automaton, folder):
    profile = automaton.profile
    text = "# Automaton " + profile.name + "\n\n"
    text = text + "_Generated by `python -m resumelens.docs_export` from the pyformlang objects._\n\n"
    text = text + "**Profile:** " + profile.display_name + ". " + profile.description + "\n\n"
    text = text + "## Diagram\n\n" + automaton_to_mermaid(automaton) + "\n\n"
    text = text + "## Formal definition\n\n" + automaton_to_markdown(automaton) + "\n"

    os.makedirs(folder, exist_ok=True)
    path = os.path.join(folder, profile.name.lower() + ".md")
    with open(path, "w", encoding="utf-8") as file:
        file.write(text)
    return path


def export_automata():
    folder = os.path.join(DOCS_DIR, "automata")
    paths = []
    for name in AUTOMATA:
        paths.append(write_automaton_doc(AUTOMATA[name], folder))
    return paths


if __name__ == "__main__":
    for path in export_transducers():
        print("written", path)
    for path in export_automata():
        print("written", path)
