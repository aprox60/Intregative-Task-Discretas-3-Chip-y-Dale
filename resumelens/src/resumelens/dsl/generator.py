# Stage 4: writes the candidate profile in the ResumeLens DSL using the results of
# the previous stages. The text is validated afterwards with the textX grammar.

from resumelens.classification.classifier import status_text

INDENT = "    "


def quote(text):
    # DSL strings use double quotes, so the ones inside the text are changed to single quotes
    return '"' + text.replace("\\", "/").replace('"', "'") + '"'


def generate_dsl(extraction, tokens, classification):
    lines = []
    lines.append("// Generated by ResumeLens")
    lines.append("candidate " + quote(extraction.name) + " {")

    lines.append(INDENT + "contact {")
    # Only the first email and phone are used, but the DSL accepts every link
    if len(extraction.emails) > 0:
        lines.append(INDENT * 2 + "email: " + extraction.emails[0])
    if len(extraction.phones) > 0:
        lines.append(INDENT * 2 + "phone: " + extraction.phones[0])
    for link in extraction.links:
        lines.append(INDENT * 2 + "link: " + link)
    lines.append(INDENT + "}")

    for experience in extraction.experience:
        lines.append(INDENT + "experience {")
        lines.append(INDENT * 2 + "years: " + str(experience.years))
        if experience.description != "":
            lines.append(INDENT * 2 + "description: " + quote(experience.description))
        lines.append(INDENT + "}")

    for education in extraction.education:
        lines.append(INDENT + "education {")
        lines.append(INDENT * 2 + "degree: " + quote(education.degree))
        lines.append(INDENT * 2 + "field: " + quote(education.field))
        if education.institution != "":
            lines.append(INDENT * 2 + "institution: " + quote(education.institution))
        lines.append(INDENT + "}")

    lines.append(INDENT + "skills { " + ", ".join(tokens) + " }")

    lines.append(INDENT + "evaluation {")
    for profile_name in classification:
        lines.append(INDENT * 2 + "profile " + profile_name + ": " + status_text(classification[profile_name]))
    lines.append(INDENT + "}")

    lines.append("}")
    return "\n".join(lines) + "\n"
