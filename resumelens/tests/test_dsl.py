import pytest

from resumelens.dsl.parser import ResumeValidationError, is_valid, parse_dsl

VALID = '''candidate "Wednesday Addams" {
    contact {
        email: wednesday@nevermore.edu
        phone: +57 300 123 4567
        link: https://wednesday.dev
    }
    experience {
        years: 3
        description: "developing web applications"
    }
    education {
        degree: "BS"
        field: "Computer Science"
        institution: "Nevermore Academy"
    }
    skills { JAVASCRIPT, REACT, NODE_JS, POSTGRESQL, GIT }
    evaluation {
        profile FULL_STACK_DEVELOPER: ACCEPTED
        profile MACHINE_LEARNING_ENGINEER: REJECTED
    }
}
'''


def error_of(text):
    with pytest.raises(ResumeValidationError) as info:
        parse_dsl(text)
    return info.value


# Valid documents

def test_valid_document_is_parsed():
    model = parse_dsl(VALID)
    assert model.name == "Wednesday Addams"
    assert model.contact.email == "wednesday@nevermore.edu"
    assert model.contact.phone == "+57 300 123 4567"
    assert model.contact.links[0].url == "https://wednesday.dev"
    assert model.experiences[0].years == 3
    assert model.educations[0].institution == "Nevermore Academy"
    assert model.skills.tokens == ["JAVASCRIPT", "REACT", "NODE_JS", "POSTGRESQL", "GIT"]
    assert model.evaluation.results[0].profile == "FULL_STACK_DEVELOPER"
    assert model.evaluation.results[0].status == "ACCEPTED"


def test_repeated_elements_are_allowed():
    text = VALID.replace(
        "    education {",
        "    experience {\n        years: 1\n    }\n    education {",
    )
    model = parse_dsl(text)
    assert len(model.experiences) == 2


def test_optional_parts_can_be_missing():
    text = VALID.replace("        phone: +57 300 123 4567\n", "").replace("        link: https://wednesday.dev\n", "")
    model = parse_dsl(text)
    assert model.contact.phone is None
    assert model.contact.links == []


def test_comments_are_ignored():
    assert is_valid("// generated by ResumeLens\n" + VALID)


# Lexical errors (a value does not match its terminal)

def test_invalid_email_is_a_lexical_error():
    error = error_of(VALID.replace("wednesday@nevermore.edu", "wednesday-nevermore"))
    assert error.kind == "Lexical"
    assert error.line == 3


def test_lowercase_skill_is_a_lexical_error():
    assert error_of(VALID.replace("JAVASCRIPT", "javascript")).kind == "Lexical"


def test_years_must_be_a_number():
    assert error_of(VALID.replace("years: 3", "years: three")).kind == "Lexical"


# Syntax errors (the structure is wrong)

def test_missing_email_is_a_syntax_error():
    error = error_of(VALID.replace("        email: wednesday@nevermore.edu\n", ""))
    assert error.kind == "Syntax"
    assert "email" in error.message


def test_wrong_bracket_is_a_syntax_error():
    assert error_of(VALID.replace("skills {", "skills [")).kind == "Syntax"


def test_unknown_status_is_a_syntax_error():
    assert error_of(VALID.replace("ACCEPTED", "MAYBE")).kind == "Syntax"


def test_unknown_profile_is_a_syntax_error():
    assert error_of(VALID.replace("BACKEND", "X").replace("MACHINE_LEARNING_ENGINEER", "DEVOPS")).kind == "Syntax"


def test_evaluation_needs_at_least_one_profile():
    text = VALID.replace("        profile FULL_STACK_DEVELOPER: ACCEPTED\n        profile MACHINE_LEARNING_ENGINEER: REJECTED\n", "")
    assert error_of(text).kind == "Syntax"


def test_sections_in_wrong_order_are_rejected():
    text = VALID.replace("    skills { JAVASCRIPT, REACT, NODE_JS, POSTGRESQL, GIT }\n", "")
    text = text.replace("    experience {", "    skills { GIT }\n    experience {")
    assert not is_valid(text)


# Semantic errors (checked with object processors)

def test_empty_name_is_rejected():
    assert error_of(VALID.replace('"Wednesday Addams"', '""')).kind == "Semantic"


def test_repeated_skill_is_rejected():
    assert error_of(VALID.replace("REACT,", "REACT, REACT,")).kind == "Semantic"


def test_too_many_years_is_rejected():
    assert error_of(VALID.replace("years: 3", "years: 99")).kind == "Semantic"


def test_profile_evaluated_twice_is_rejected():
    error = error_of(VALID.replace("profile MACHINE_LEARNING_ENGINEER", "profile FULL_STACK_DEVELOPER"))
    assert error.kind == "Semantic"
    assert error.line == 19
